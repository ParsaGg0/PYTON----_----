def sequence_term(n):
    a = 3  # جمله‌ی اول
    for i in range(1, n):   # از جمله‌ی دوم تا n‌ام
        a = (a + 1) / 4
    return a

# 🧪 تست برنامه
n = int(input("شماره جمله را وارد کنید: "))
print(f"جمله‌ی {n}ام دنباله برابر است با:", sequence_term(n))
